create or replace function private.complete_profile_impl(
  p_full_name text,
  p_role text,
  p_phone text default null,
  p_city text default null
)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_role text := lower(btrim(coalesce(p_role, '')));
  v_profile public.profiles;
begin
  if v_uid is null then
    raise exception 'No autenticado';
  end if;

  if nullif(btrim(coalesce(p_full_name, '')), '') is null then
    raise exception 'El nombre es obligatorio';
  end if;

  if v_role not in ('client', 'professional') then
    raise exception 'Rol no permitido';
  end if;

  insert into public.profiles (id, email, full_name, role, phone, city)
  select
    u.id,
    u.email,
    btrim(p_full_name),
    v_role,
    nullif(btrim(coalesce(p_phone, '')), ''),
    nullif(btrim(coalesce(p_city, '')), '')
  from auth.users u
  where u.id = v_uid
  on conflict (id) do update set
    email = coalesce(public.profiles.email, excluded.email),
    full_name = excluded.full_name,
    role = excluded.role,
    phone = excluded.phone,
    city = excluded.city
  returning * into v_profile;

  if v_profile.id is null then
    raise exception 'Usuario no encontrado';
  end if;

  return v_profile;
end;
$$;

