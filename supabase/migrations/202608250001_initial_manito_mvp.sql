create extension if not exists pgcrypto;
create schema if not exists private;

revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text not null default '',
  role text not null default 'client'
    check (role in ('client', 'professional', 'admin')),
  phone text,
  city text,
  is_available boolean not null default false,
  lat double precision,
  lng double precision,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  emoji text not null default 'wrench',
  base_price numeric(12, 2),
  active boolean not null default true
);

create table if not exists public.professional_services (
  professional_id uuid not null references public.profiles(id) on delete cascade,
  service_id bigint not null references public.services(id) on delete cascade,
  price_from numeric(12, 2),
  primary key (professional_id, service_id)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.profiles(id) on delete restrict,
  professional_id uuid references public.profiles(id) on delete set null,
  service_id bigint not null references public.services(id) on delete restrict,
  description text not null,
  address text not null,
  mode text not null default 'immediate'
    check (mode in ('immediate', 'scheduled', 'quote')),
  scheduled_at timestamptz,
  status text not null default 'open'
    check (status in ('open', 'accepted', 'en_camino', 'en_sitio', 'completed', 'cancelled')),
  price numeric(12, 2),
  client_lat double precision,
  client_lng double precision,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  accepted_at timestamptz,
  completed_at timestamptz
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_client
  on public.orders(client_id, created_at desc);
create index if not exists idx_orders_professional
  on public.orders(professional_id, created_at desc);
create index if not exists idx_orders_open
  on public.orders(status, service_id, created_at desc)
  where status = 'open';
create index if not exists idx_messages_order
  on public.messages(order_id, created_at);

