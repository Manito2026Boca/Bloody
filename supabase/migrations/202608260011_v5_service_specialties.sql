create table if not exists public.specialties (
  id bigint generated by default as identity primary key,
  service_id bigint not null references public.services(id) on delete cascade,
  name text not null,
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (service_id, name),
  unique (id, service_id)
);

create table if not exists public.professional_specialties (
  professional_id uuid not null,
  service_id bigint not null,
  specialty_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (professional_id, specialty_id),
  foreign key (professional_id, service_id)
    references public.professional_services(professional_id, service_id)
    on delete cascade,
  foreign key (specialty_id, service_id)
    references public.specialties(id, service_id)
    on delete cascade
);

create index if not exists idx_specialties_service
  on public.specialties(service_id, position, name)
  where active;

create index if not exists idx_professional_specialties_professional
  on public.professional_specialties(professional_id, service_id);

