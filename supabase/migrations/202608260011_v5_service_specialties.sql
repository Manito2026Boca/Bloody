select services.id, catalog.specialty_name, catalog.position, true
from catalog
join public.services on services.slug = catalog.slug
on conflict (service_id, name) do update set
  position = excluded.position,
  active = true;

alter table public.specialties enable row level security;
alter table public.professional_specialties enable row level security;

revoke all on public.specialties from anon, authenticated;
revoke all on public.professional_specialties from anon, authenticated;

grant select on public.specialties to authenticated;
grant select, insert, delete on public.professional_specialties to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists specialties_select on public.specialties;
create policy specialties_select on public.specialties
for select to authenticated
using (
  active = true
  and exists (
    select 1
    from public.services s
    where s.id = specialties.service_id
      and s.active = true
  )
);

drop policy if exists professional_specialties_select on public.professional_specialties;
create policy professional_specialties_select on public.professional_specialties
for select to authenticated
using (true);

drop policy if exists professional_specialties_insert_own on public.professional_specialties;
create policy professional_specialties_insert_own on public.professional_specialties
for insert to authenticated
with check (professional_id = (select auth.uid()));

drop policy if exists professional_specialties_delete_own on public.professional_specialties;
create policy professional_specialties_delete_own on public.professional_specialties
for delete to authenticated
using (professional_id = (select auth.uid()));
